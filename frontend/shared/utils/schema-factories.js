/**
 * schema-factories.js
 * Standardizes the creation of all data objects before inserting them into the DB.
 */

/**
 * Creates a user object with the specified parameters.
 * @param { string } firstName - The user's first name.
 * @param { string } lastName - The user's last name.
 * @param { string } username - The user's unique username.
 * @param { string } email - The user's unique email address.
 * @param { string } password - The password for the user.
 * @param { string } role - The user's role, either 'admin' or 'user'.
 * @returns { Object } A standardized user object ready for insertion into the database. 
*/
export function createUserObject(firstName, lastName, username, email, password, role) {
    return {
        firstName: firstName,
        lastName: lastName,
        username: username,
        email: email,
        password: password,
        role: role,
        savedRecipes: [], // Defaults to empty array
        token: null // Defaults to null until login
    }
}

/**
 * Creates a recipe object with the specified parameters.
 * @param { string } name - The name of the recipe.
 * @param { string } description - A brief description of the recipe.
 * @param { string } courseType - The type of course (e.g. 'Appetizers', 'Main', 'Dessert').
 * @param { Array } ingredientsArray - An array of ingredient objects.
 * @param { string } imageURL - The URL of the recipe's image (optional).
 * @returns { Object } - A standardized recipe object ready for insertion into the database.
 */
export function createRecipeObject(name, description, courseType, ingredientsArray, imageURL = "") {
    return {
        // Note: id will be automatically generated by db-recipes.js during insertion.
        name: name,
        description: description,
        courseType: courseType,
        ingredients: ingredientsArray,
        image: imageURL
    }
}

/** 
 * Creates an ingredient object with the specified parameters.
 * @param { string } name - The name of the ingredient.
 * @param { number } quantity - The quantity of the ingredient.
 * @param { string } unit - The unit of measurement for the ingredient (e.g. 'cups', 'grams').
 * @returns { Object } - A standardized ingredient object ready for inclusion in a recipe.
 */
export function createIngredientObject(name, quantity, unit) {
    return {
        name: name,
        quantity: quantity,
        unit: unit
    }
}